import json

def flatten(d, prefix=''):
    items = {}
    for k, v in d.items():
        key = prefix + k
        if isinstance(v, dict):
            items.update(flatten(v, key + '.'))
        else:
            items[key] = v
    return items

def set_nested(d, key, value):
    parts = key.split('.')
    for part in parts[:-1]:
        if part not in d:
            d[part] = {}
        elif not isinstance(d[part], dict):
            d[part] = {}
        d = d[part]
    d[parts[-1]] = value

